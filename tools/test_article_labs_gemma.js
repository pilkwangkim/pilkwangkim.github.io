'use strict';
const assert = require('node:assert/strict');
const g = require('../assets/js/article-labs-gemma.js');
assert.equal(g.normalizeLimit(0, false), 10);
assert.equal(g.normalizeLimit(0, true), 0);
assert.equal(g.normalizeLimit(null, true), 10);
assert.equal(g.normalizeLimit(5, true), 5);
assert.equal(g.admittedCalls(32768, 8192, 18033, 119), 55);
assert.equal(g.admittedCalls(32768, 8192, 24578, 119), 0);
assert.equal(g.admittedCalls(100, 20, 80, 1), 1);
assert(g.admittedCalls(32768, 4096, 18033, 119) > 55);
assert.equal(g.parsedPath('read_file{filepath:<|"|>x.py<|"|>,start_line:4}'), 'x.py');
assert.equal(g.parsedPath('read_file{filepath:<|"|>x.py",start_line":4<|"|>}'), 'x.py",start_line":4');
assert(Math.abs(g.phi(0) - .5) < 1e-6);
const ref = g.finishChance(120, 20, 5, 2.5), slower = g.finishChance(120, 20, 5, 2.5, 1.18);
assert(ref > .99 && slower > .39 && slower < .41);
assert(slower * 12 / 58 < ref * 11 / 58);
assert.equal(g.finishChance(120, 20, 5, 0), 1);
assert.deepEqual(g.paired(2, 2, 3, 5), { n: 12, baseline: 4, candidate: 5, delta: 1 / 12, changed: 5 });
assert.equal(g.paired(0, 0, 0, 0).delta, 0);
console.log('Gemma article labs: contract, parser, admission, timing, and pairing invariants pass.');

'use strict';
const assert = require('node:assert/strict');
const p = require('../assets/js/article-labs-predictive.js');
const cm = p.confusion(p.toy, .5);
assert.deepEqual([cm.tp, cm.fp, cm.fn, cm.tn], [4, 2, 2, 4]);
assert.equal(p.confusion(p.toy, 0).tp, 6);
assert.equal(p.confusion(p.toy, 1).precision, null);
assert.equal(p.confusion([{ p: .5, y: 1 }], .5).tp, 1);
assert(Math.abs(p.auc(p.toy) - 29 / 36) < 1e-12);
assert.equal(p.auc([{ p: .5, y: 0 }, { p: .5, y: 1 }]), .5);
assert.equal(p.targetEncoding(10, .6, 0, .2), .6);
assert(Math.abs(p.targetEncoding(10, .6, 80, .2) - 22 / 90) < 1e-12);
assert(Math.abs(p.targetEncoding(10, .6, 300, .2) - .2) < Math.abs(p.targetEncoding(10, .6, 80, .2) - .2));
assert.equal(p.fluxRatio(0), 1);
assert(Math.abs(p.fluxRatio(2.5) - .1) < 1e-12);
assert(Math.abs(p.fluxRatio(1.481) * p.fluxRatio(-1.481) - 1) < 1e-12);
const decision = p.classDecision([48, 12, 40], p.selectedMultipliers);
assert.equal(decision.before, 0);
assert.equal(decision.after, 2);
assert.equal(p.classDecision([48, 12, 40], [1, 1, 1]).after, 0);
assert(Math.abs(p.classDecision([0, 0, 0], [1, 1, 1]).probabilities.reduce((a, b) => a + b) - 1) < 1e-12);
assert.equal(p.alignedCutoff(93, 97), 93);
assert.equal(p.inSnapshot(2026, 94, 93), false);
assert.equal(p.inSnapshot(2026, 93, 93), true);
assert.equal(p.inSnapshot(2025, 140, 93), true);
assert.equal(p.inSnapshot(2027, 1, 93), false);
assert.equal(p.seasonRole(2024, 2025), 'train');
assert.equal(p.seasonRole(2025, 2025), 'validation');
assert.equal(p.seasonRole(2026, 2025), 'excluded');
console.log('Predictive article labs: threshold, shrinkage, flux, decision, and temporal-boundary invariants pass.');
